const BY_ID = new Map(EXERCISE_LIST.map((e) => [e.id, e]));

/** Peut renvoyer undefined pour un exercice retiré du programme mais présent dans l'historique. */
export function findExercise(id: string): Exercise | undefined {
  return BY_ID.get(id);
}

export function exercise(id: string): Exercise {
  const found = BY_ID.get(id);
  if (!found) throw new Error(`Exercice inconnu : ${id}`);
  return found;
}

/** Alternatives d'un exercice du programme, pour remplacer une machine occupée. */
export function alternativesOf(id: string): Exercise[] {
  return (ALTERNATIVES[id] ?? []).map(exercise);
}
